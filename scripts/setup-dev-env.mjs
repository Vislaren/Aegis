#!/usr/bin/env node
// Generates development-only keys and environment files (git-ignored). Never prints secret values.
//   services/<service>/.env           for running a service directly on the host
//   infrastructure/docker/services.env for the compose `services` profile
// Re-running keeps existing files unless --force is passed.

import { generateKeyPairSync, randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const force = process.argv.includes('--force');

function jwk(kid) {
  const { privateKey } = generateKeyPairSync('ec', { namedCurve: 'P-256' });
  return { ...privateKey.export({ format: 'jwk' }), kid, alg: 'ES256' };
}
const publicOf = ({ d: _d, ...rest }) => ({ ...rest, use: 'sig' });

const services = [
  'identity-service',
  'administration-service',
  'audit-service',
  'realtime-gateway',
];
const keys = Object.fromEntries(services.map((s) => [s, jwk(s)]));
const accessKey = jwk(`access-${new Date().toISOString().slice(0, 10)}`);
const trusted = (callers) =>
  JSON.stringify(Object.fromEntries(callers.map((c) => [c, publicOf(keys[c])])));

const common = {
  NODE_ENV: 'development',
  LOG_LEVEL: 'info',
  ACCESS_TOKEN_ISSUER: 'https://identity.aegis.local',
  BROKER: 'rabbitmq',
};
const host = {
  AMQP_URL: 'amqp://aegis:aegis_dev@localhost:5672',
  IDENTITY_JWKS_URL: 'http://localhost:3001/internal/v1/.well-known/jwks.json',
};
const docker = {
  AMQP_URL: 'amqp://aegis:aegis_dev@rabbitmq:5672',
  IDENTITY_JWKS_URL: 'http://identity-service:3001/internal/v1/.well-known/jwks.json',
};

const perService = {
  'identity-service': {
    PORT: '3001',
    DATABASE_URL: 'postgresql://identity_app:identity_app_dev@localhost:5432/aegis_identity',
    MIGRATION_DATABASE_URL:
      'postgresql://identity_owner:identity_owner_dev@localhost:5432/aegis_identity',
    ACCESS_TOKEN_SIGNING_KEY: JSON.stringify(accessKey),
    OTP_PEPPER: randomBytes(32).toString('base64url'),
    MFA_ENCRYPTION_KEY: randomBytes(32).toString('base64'),
    DELIVERY: 'smtp',
    SMTP_URL: 'smtp://localhost:1025',
    APP_PUBLIC_URL: 'http://localhost:8081',
    COOKIE_SECURE: 'false',
    TRUSTED_SERVICE_KEYS: trusted(['administration-service', 'audit-service', 'realtime-gateway']),
  },
  'administration-service': {
    PORT: '3002',
    DATABASE_URL:
      'postgresql://administration_app:administration_app_dev@localhost:5432/aegis_administration',
    MIGRATION_DATABASE_URL:
      'postgresql://administration_owner:administration_owner_dev@localhost:5432/aegis_administration',
    IDENTITY_INTERNAL_URL: 'http://localhost:3001',
    TRUSTED_SERVICE_KEYS: trusted(['audit-service', 'realtime-gateway']),
  },
  'audit-service': {
    PORT: '3003',
    DATABASE_URL: 'postgresql://audit_app:audit_app_dev@localhost:5432/aegis_audit',
    MIGRATION_DATABASE_URL: 'postgresql://audit_owner:audit_owner_dev@localhost:5432/aegis_audit',
    ADMINISTRATION_INTERNAL_URL: 'http://localhost:3002',
  },
  'realtime-gateway': {
    PORT: '3004',
    ADMINISTRATION_INTERNAL_URL: 'http://localhost:3002',
    IDENTITY_INTERNAL_URL: 'http://localhost:3001',
    ALLOWED_ORIGINS: 'http://localhost:8081',
  },
};

const render = (vars) =>
  `# Generated by scripts/setup-dev-env.mjs for LOCAL DEVELOPMENT ONLY. Do not commit.\n${Object.entries(
    vars,
  )
    .map(([k, v]) => `${k}=${/[\s"'#{]/.test(v) ? `'${v}'` : v}`)
    .join('\n')}\n`;

function write(path, content) {
  if (existsSync(path) && !force) {
    console.log(`kept existing ${path.replace(root, '')} (use --force to regenerate)`);
    return;
  }
  writeFileSync(path, content, { mode: 0o600 });
  console.log(`wrote ${path.replace(root, '')}`);
}

for (const service of services) {
  write(
    join(root, 'services', service, '.env'),
    render({
      ...common,
      ...host,
      SERVICE_NAME: service,
      SERVICE_PRIVATE_KEY: JSON.stringify(keys[service]),
      ...perService[service],
    }),
  );
}
write(
  join(root, 'services', 'api-gateway', '.env'),
  render({
    NODE_ENV: 'development',
    LOG_LEVEL: 'info',
    PORT: '3000',
    IDENTITY_URL: 'http://localhost:3001',
    ADMINISTRATION_URL: 'http://localhost:3002',
    AUDIT_URL: 'http://localhost:3003',
    REALTIME_URL: 'http://localhost:3004',
    ALLOWED_ORIGINS: 'http://localhost:8081',
  }),
);

// Compose: per-service keys are injected through one env file with prefixed names is not supported by
// compose, so the shared file carries the values every container may read and per-service
// `environment:` blocks select the rest. Private keys are therefore written per service below.
const composeShared = {
  ...common,
  ...docker,
  ...{ APP_PUBLIC_URL: 'http://localhost:8081', ALLOWED_ORIGINS: 'http://localhost:8081' },
};
write(join(root, 'infrastructure', 'docker', 'services.env'), render(composeShared));
for (const service of services) {
  const { PORT: _p, DATABASE_URL: _d, MIGRATION_DATABASE_URL: _m, ...rest } = perService[service];
  const dockerOnly = Object.fromEntries(
    Object.entries(rest).map(([k, v]) => [
      k,
      v.replace(
        /localhost:(\d+)/g,
        (_, port) =>
          ({
            3001: 'identity-service:3001',
            3002: 'administration-service:3002',
            1025: 'mailpit:1025',
          })[port] ?? `localhost:${port}`,
      ),
    ]),
  );
  write(
    join(root, 'infrastructure', 'docker', `${service}.env`),
    render({ SERVICE_PRIVATE_KEY: JSON.stringify(keys[service]), ...dockerOnly }),
  );
}
console.log(
  'Development environment files are ready. They contain development-only keys; never reuse them elsewhere.',
);
